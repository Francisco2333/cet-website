async function databaseRecords(page) {
  return page.evaluate(async () => {
    const db = await new Promise((resolve, reject) => { const r = indexedDB.open("cet-local-data", 1); r.onsuccess = () => resolve(r.result); r.onerror = reject; });
    const records = await new Promise((resolve, reject) => { const tx = db.transaction("practices"); const r = tx.objectStore("practices").getAll(); tx.oncomplete = () => resolve(r.result); tx.onerror = reject; });
    db.close(); return records;
  });
}

